#!/usr/bin/env node
'use strict';

// The root document remains the authored source. Route entries are deterministic
// publication artifacts so GitHub Pages never needs an SPA fallback or a rewrite.
const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.resolve(__dirname, '..');
const BEGIN = '<!-- BEGIN GENERATED ROUTES -->';
const END = '<!-- END GENERATED ROUTES -->';
const GENERATED_NOTICE = '<!-- Generated from index.html by scripts/build.cjs. Do not edit this file. -->';
const VIEW_NAMES = ['home', 'cv', 'score'];
const LANGUAGE_NAMES = { pl: 'Polski', en: 'English', de: 'Deutsch' };

function escapeHTML(value) {
  return String(value).replace(/&/g, '&amp;').replace(/</g, '&lt;')
    .replace(/>/g, '&gt;').replace(/"/g, '&quot;').replace(/'/g, '&#39;');
}

function escapeRegExp(value) {
  return String(value).replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function attributePattern(name) {
  return new RegExp('\\s+' + escapeRegExp(name) + '(?:\\s*=\\s*(?:"[^"]*"|\'[^\']*\'|[^\\s>]+))?(?=\\s|/?>)', 'i');
}

function getAttribute(tag, name) {
  const match = tag.match(new RegExp('\\s+' + escapeRegExp(name) + '(?:\\s*=\\s*(?:"([^"]*)"|\'([^\']*)\'|([^\\s>]+)))?(?=\\s|/?>)', 'i'));
  if (!match) return null;
  return (match[1] === undefined ? match[2] === undefined ? match[3] || '' : match[2] : match[1])
    .replace(/&amp;/g, '&').replace(/&quot;/g, '"').replace(/&#39;/g, "'");
}

function setAttribute(tag, name, value) {
  const attribute = ' ' + name + (value === true ? '' : '="' + escapeHTML(value) + '"');
  const pattern = attributePattern(name);
  return pattern.test(tag) ? tag.replace(pattern, () => attribute)
    : tag.replace(/\s*\/?>(?=$)/, ending => attribute + ending);
}

function removeAttribute(tag, name) {
  return tag.replace(attributePattern(name), '');
}

// Leave inline engine code, shaders, styles and source-viewer strings byte-for-byte
// intact. Only actual HTML opening tags are candidates for attribute updates.
function mapTags(html, transform) {
  return html.replace(/<!--[\s\S]*?-->|<(script|style)\b[^>]*>[\s\S]*?<\/\1\s*>|<\/?[A-Za-z](?:[^"'<>]|"[^"]*"|'[^']*')*>/gi, token => {
    if (/^<!--|^<\/|^<(?:script|style)\b/i.test(token)) return token;
    const name = token.match(/^<([\w:-]+)/)?.[1].toLowerCase();
    return name ? transform(token, name) : token;
  });
}

function replaceScript(html, id, update) {
  const pattern = new RegExp('(<script\\b(?=[^>]*\\bid="' + escapeRegExp(id) + '")[^>]*>)([\\s\\S]*?)(</script>)', 'i');
  if (!pattern.test(html)) throw new Error('Missing required script #' + id);
  return html.replace(pattern, (_, start, content, end) => start + update(content) + end);
}

function jsonForScript(value) {
  return JSON.stringify(value).replace(/</g, '\\u003c').replace(/\u2028/g, '\\u2028').replace(/\u2029/g, '\\u2029');
}

function loadInputs(rootDir) {
  const source = fs.readFileSync(path.join(rootDir, 'index.html'), 'utf8');
  const rawConfig = JSON.parse(fs.readFileSync(path.join(rootDir, 'site.config.json'), 'utf8'));
  const modulePath = path.join(rootDir, 'src', 'routes.cjs');
  const moduleSource = fs.readFileSync(modulePath, 'utf8').replace(/\s*$/, '\n');
  const routes = require(modulePath);
  const config = routes.normalizeConfig(rawConfig); // Fail early on an invalid publication contract.
  let locales;
  replaceScript(source, 'site-locales', text => { locales = JSON.parse(text); return text; });
  if (!locales?.meta?.[rawConfig.defaultLanguage]) throw new Error('Missing default-language metadata');
  return { source, config, routes, moduleSource, locales };
}

function routeURL(inputs, view, language, format) {
  const lang = language || inputs.config.defaultLanguage;
  return inputs.routes.serializeRoute({ view, lang, uiLang: lang, format: format || 'html', hash: '' }, inputs.config);
}

function absoluteRoute(inputs, view, language) {
  return new URL(routeURL(inputs, view, language), inputs.config.siteOrigin).href;
}

function injectRoutes(source, config, moduleSource) {
  const start = source.indexOf(BEGIN), end = source.indexOf(END);
  if (start < 0 || end < start || source.indexOf(BEGIN, start + BEGIN.length) !== -1
    || source.indexOf(END, end + END.length) !== -1) {
    throw new Error('index.html must contain exactly one ordered BEGIN GENERATED ROUTES / END GENERATED ROUTES block');
  }
  if (/<\/script\s*>/i.test(moduleSource)) throw new Error('Route module contains an unsafe inline script terminator');
  const generated = BEGIN + '\n<script id="site-config">window.GUZICZAK_SITE_CONFIG=' + jsonForScript(config)
    + ';</script>\n<script id="site-route-model">\n' + moduleSource + '</script>\n' + END;
  return source.slice(0, start) + generated + source.slice(end + END.length);
}

function normalizeLocaleURLs(source, inputs) {
  return replaceScript(source, 'site-locales', content => {
    const locales = JSON.parse(content);
    for (const language of inputs.config.languages) {
      const home = absoluteRoute(inputs, 'home', language);
      if (locales.dom?.n2?.[language]?.attrs) locales.dom.n2[language].attrs.href = home;
      if (locales.dom?.n5?.[language]?.attrs) locales.dom.n5[language].attrs.content = home;
    }
    return jsonForScript(locales);
  });
}

function metadata(inputs, view) {
  const language = inputs.config.defaultLanguage;
  const page = view === 'home' ? {
    title: inputs.locales.meta[language].title,
    description: inputs.locales.dom.n0[language].attrs.content
  } : inputs.config.pages?.[view]?.[language];
  if (!page?.title || !page?.description) throw new Error('Missing page metadata for ' + view + ':' + language);
  return { title: page.title, description: page.description, canonical: absoluteRoute(inputs, view) };
}

function updateMetadata(source, inputs, view) {
  const meta = metadata(inputs, view);
  const headMatch = source.match(/<head\b[^>]*>[\s\S]*?<\/head>/i);
  if (!headMatch) throw new Error('Missing head element');
  let head = headMatch[0];
  const titlePattern = /(<title\b[^>]*>)[\s\S]*?<\/title>/i;
  if (!titlePattern.test(head)) throw new Error('Missing document title');
  head = head.replace(titlePattern, (_, opening) => (view === 'home' ? opening : removeAttribute(opening, 'data-l10n')) + escapeHTML(meta.title) + '</title>');
  const found = new Set();
  head = mapTags(head, (tag, name) => {
    if (name === 'meta') {
      const key = getAttribute(tag, 'property') || getAttribute(tag, 'name');
      const values = { description: meta.description, 'og:title': meta.title, 'og:description': meta.description,
        'og:url': meta.canonical, 'twitter:title': meta.title, 'twitter:description': meta.description };
      if (Object.hasOwn(values, key)) {
        found.add(key);
        tag = setAttribute(tag, 'content', values[key]);
        if (view !== 'home') tag = removeAttribute(tag, 'data-l10n');
      }
    }
    if (name === 'link') {
      const rel = getAttribute(tag, 'rel');
      if (rel === 'canonical') {
        found.add('canonical');
        tag = setAttribute(tag, 'href', meta.canonical);
        if (view !== 'home') tag = removeAttribute(tag, 'data-l10n');
      } else if (rel === 'alternate' && getAttribute(tag, 'hreflang')) {
        const lang = getAttribute(tag, 'hreflang');
        if (lang === 'x-default' || inputs.config.languages.includes(lang)) {
          tag = setAttribute(tag, 'href', absoluteRoute(inputs, view, lang === 'x-default' ? inputs.config.defaultLanguage : lang));
        }
      }
    }
    return tag;
  });
  for (const key of ['description', 'og:title', 'og:description', 'og:url', 'canonical']) {
    if (!found.has(key)) throw new Error('Missing metadata field: ' + key);
  }
  head = head.replace(/(<script\b[^>]*\btype="application\/ld\+json"[^>]*>)([\s\S]*?)(<\/script>)/gi, (_, start, content, end) => {
    const data = JSON.parse(content);
    if (data['@type'] === 'Person') data.url = absoluteRoute(inputs, 'home');
    return start + jsonForScript(data) + end;
  });
  return source.slice(0, headMatch.index) + head + source.slice(headMatch.index + headMatch[0].length);
}

function rewriteLinks(source, inputs, view) {
  return mapTags(source, (tag, name) => {
    if (name !== 'a') return tag;
    if (view !== 'home' && (getAttribute(tag, 'class') || '').split(/\s+/).includes('skip-content')) {
      return setAttribute(tag, 'href', '#' + view + '-title');
    }
    const cvFormat = getAttribute(tag, 'data-cv-open');
    const scoreFormat = getAttribute(tag, 'data-score-open');
    const language = getAttribute(tag, 'data-site-language');
    if (cvFormat !== null) return setAttribute(tag, 'href', routeURL(inputs, 'cv', undefined, cvFormat));
    if (scoreFormat !== null) return setAttribute(tag, 'href', routeURL(inputs, 'score', undefined, scoreFormat));
    if (language && inputs.config.languages.includes(language)) return setAttribute(tag, 'href', routeURL(inputs, view, language));
    const href = getAttribute(tag, 'href');
    if (view !== 'home' && href?.startsWith('#') && !href.startsWith('#/')) {
      return setAttribute(tag, 'href', routeURL(inputs, 'home') + href);
    }
    return tag;
  });
}

function documentFallback(inputs, view) {
  const config = inputs.config;
  const original = resource => new URL(resource, config.documentOrigin).href;
  let content = '<p>Możesz otworzyć oryginalne dokumenty bez JavaScript.</p><ul>';
  if (view === 'cv') {
    for (const language of config.languages) {
      const documents = config.documents.cv[language];
      if (!documents?.html || !documents?.pdf) throw new Error('Missing original CV links for ' + language);
      content += '<li><span lang="' + escapeHTML(language) + '">' + escapeHTML(LANGUAGE_NAMES[language] || language.toUpperCase())
        + '</span>: <a href="' + escapeHTML(original(documents.html)) + '" hreflang="' + escapeHTML(language) + '">HTML</a> · '
        + '<a href="' + escapeHTML(original(documents.pdf)) + '" hreflang="' + escapeHTML(language) + '">PDF</a></li>';
    }
  } else {
    content += '<li><a href="' + escapeHTML(original(config.documents.score.html)) + '">Otwórz oryginalny zapis nutowy</a></li>'
      + '<li><a href="' + escapeHTML(original(config.documents.score.pdf)) + '">Otwórz lub pobierz partyturę PDF</a></li>';
  }
  content += '</ul><nav aria-label="Nawigacja dokumentów"><a href="' + escapeHTML(routeURL(inputs, 'home')) + '">Strona główna</a> · '
    + '<a href="' + escapeHTML(routeURL(inputs, 'cv')) + '">CV</a> · '
    + '<a href="' + escapeHTML(routeURL(inputs, 'score')) + '">Partytura</a></nav>';
  return '<noscript><style>body:is(.route-cv,.route-score){overflow:auto}.cv-view{height:auto;min-height:calc(100vh - var(--head))}'
    + '.cv-actions-bar,.cv-bottom-bar{display:none!important}.cv-document-panel{display:block;overflow:visible;min-height:240px}'
    + '#cv-frame-host,#score-frame-host{display:block!important;height:auto!important;overflow:visible!important}'
    + '.document-static-fallback{padding:32px;color:var(--fg);line-height:1.8}.document-static-fallback a{color:var(--gold);text-decoration:underline}'
    + '.document-static-fallback ul{padding-left:24px;margin:20px 0}.document-static-fallback li{margin:8px 0}'
    + '</style><section class="document-static-fallback" aria-label="Oryginalne dokumenty">' + content + '</section></noscript>';
}

function documentEntry(source, inputs, view) {
  let activeFound = false, hostFound = false;
  let output = mapTags(source, (tag, name) => {
    const id = getAttribute(tag, 'id');
    if (name === 'html') tag = setAttribute(tag, 'data-intro', 'manual');
    if (name === 'body') {
      const classes = (getAttribute(tag, 'class') || '').split(/\s+/).filter(value => value && !['intro', 'booting', 'handoff', 'route-cv', 'route-score'].includes(value));
      classes.push('route-' + view);
      tag = setAttribute(setAttribute(tag, 'class', classes.join(' ')), 'data-view', view);
    }
    if (id === 'site' || id === 'cv-view' || id === 'score-view') {
      if (id === view + '-view') {
        activeFound = true;
        tag = removeAttribute(removeAttribute(tag, 'hidden'), 'inert');
      } else tag = setAttribute(setAttribute(tag, 'hidden', true), 'inert', true);
    }
    if (id === view + '-frame-host') {
      hostFound = true;
      tag += documentFallback(inputs, view);
    }
    return tag;
  });
  if (!activeFound || !hostFound) throw new Error('Missing view or document host for ' + view);
  output = updateMetadata(output, inputs, view);
  output = rewriteLinks(output, inputs, view);
  return output.replace(/<!doctype html>/i, match => match + '\n' + GENERATED_NOTICE);
}

function renderSite({ rootDir = ROOT } = {}) {
  rootDir = path.resolve(rootDir);
  const inputs = loadInputs(rootDir);
  let home = injectRoutes(inputs.source, inputs.config, inputs.moduleSource);
  home = normalizeLocaleURLs(home, inputs);
  home = updateMetadata(home, inputs, 'home');
  home = rewriteLinks(home, inputs, 'home');
  const output = new Map([['index.html', home]]);
  for (const view of VIEW_NAMES.slice(1)) {
    const directory = inputs.config.routes[view];
    if (!/^[a-zA-Z0-9_-]+\/$/.test(directory)) throw new Error('Static document routes must be one safe directory ending with /');
    output.set(directory + 'index.html', documentEntry(home, inputs, view));
  }
  output.set('.nojekyll', '');
  return output;
}

function build({ rootDir = ROOT, outputDir = rootDir, check = false } = {}) {
  const files = renderSite({ rootDir });
  const changed = [];
  for (const [relative, content] of files) {
    const target = path.join(outputDir, relative);
    const existing = fs.existsSync(target) ? fs.readFileSync(target, 'utf8') : null;
    if (existing === content) continue;
    changed.push(relative);
    if (!check) {
      fs.mkdirSync(path.dirname(target), { recursive: true });
      fs.writeFileSync(target, content, 'utf8');
    }
  }
  return { files, changed, check, outputDir: path.resolve(outputDir) };
}

function main(argv) {
  let check = false, outputDir = ROOT;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === '--check') check = true;
    else if (argv[i] === '--out-dir' && argv[i + 1]) outputDir = path.resolve(argv[++i]);
    else throw new Error('Usage: node scripts/build.cjs [--check] [--out-dir DIRECTORY]');
  }
  const result = build({ check, outputDir });
  if (check && result.changed.length) {
    console.error('Generated files are stale: ' + result.changed.join(', '));
    console.error('Run node scripts/build.cjs and commit the regenerated files.');
    process.exitCode = 1;
  } else console.log(check ? 'Generated routes are up to date.' : result.changed.length ? 'Generated: ' + result.changed.join(', ') : 'Generated routes are already up to date.');
}

module.exports = { renderSite, build };
if (require.main === module) {
  try { main(process.argv.slice(2)); }
  catch (error) { console.error('Build failed: ' + error.message); process.exitCode = 1; }
}
